class RwType(enum.Enum):
    """fio workload type; value is the fio ``--readwrite=`` token."""

    RAND = "randrw"
    SEQ = "rw"
    READ = "read"
    WRITE = "write"
    TRIM = "trim"
    RANDREAD = "randread"
    RANDWRITE = "randwrite"
    RANDTRIM = "randtrim"
    TRIMWRITE = "trimwrite"


class IoEngine(enum.Enum):
    """fio I/O engine; value is the fio ``--ioengine=`` token."""

    SYNC = "sync"
    PSYNC = "psync"
    VSYNC = "vsync"
    PVSYNC = "pvsync"
    PVSYNC2 = "pvsync2"
    LIBAIO = "libaio"
    POSIXAIO = "posixaio"


# Shared helpers (promoted FROM this module to pyte.tools._tool/_units;
# aliased so internal call sites and tests keep their names).
from pyte.tools._tool import coerce_enum as _coerce  # noqa: E402
from pyte.tools._units import parse_size as _parse_size  # noqa: E402


@dataclass(frozen=True)
class Opts:
    """fio job options.

    Parameters
    ----------
    filename:
        Path to the data file (required).
    name:
        Job name (default ``"pyte.fio"``).
    blocksize:
        Block size in bytes (default 4096).
    numjobs:
        Number of parallel jobs (default 1).
    iodepth:
        I/O queue depth (default 1; psync caps at 1).
    runtime:
        Runtime in seconds; 0 means no time limit / run to completion.
        When > 0, ``--runtime=<N>s --time_based`` is added.
    rwmixread:
        Read percentage for mixed workloads (default 50).
    rwtype:
        Workload type; a :class:`RwType` member (e.g. ``RwType.RAND``)
        or the equivalent lowercase name string (e.g. ``"rand"``).
        Valid names: ``rand``, ``seq``, ``read``, ``write``, ``trim``,
        ``randread``, ``randwrite``, ``randtrim``, ``trimwrite``.
    ioengine:
        I/O engine; an :class:`IoEngine` member (e.g. ``IoEngine.PSYNC``)
        or the equivalent lowercase name string (e.g. ``"psync"``).
        Valid names: sync, psync, vsync, pvsync, pvsync2, libaio,
        posixaio.  (rbd is excluded: its extra options are out of
        scope.)
    direct:
        Use O_DIRECT (default False).
    size:
        Data file size as int bytes or string (``"4k"``, ``"16m"``,
        ``"1g"``).  None leaves ``--size`` unset.
    extra_args:
        Raw extra arguments appended at the end (space-split per
        user_argument() logic in fio_internal.c).
    """
    filename: str
    name: str = "pyte.fio"
    blocksize: int = 4096
    numjobs: int = 1
    iodepth: int = 1
    runtime: int = 0
    rwmixread: int = 50
    rwtype: "RwType | str" = RwType.SEQ
    ioengine: "IoEngine | str" = IoEngine.PSYNC
    direct: bool = False
    size: str | int | None = None
    extra_args: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        if not self.filename:
            raise ValueError("Opts.filename is required")
        object.__setattr__(self, "rwtype",
                           _coerce(RwType, "rwtype", self.rwtype))
        object.__setattr__(self, "ioengine",
                           _coerce(IoEngine, "ioengine", self.ioengine))
        # Validate size format (parse and discard)
        _parse_size(self.size)

    def to_argv(self) -> list[str]:
        """Build the fio command-line argument list (without argv[0]).

        Mirrors tapi_fio fio_binds order from fio_internal.c.
        """
        argv: list[str] = []
        argv.append(f"--name={self.name}")
        argv.append(f"--filename={self.filename}")
        argv.append(f"--blocksize={self.blocksize}")
        argv.append(f"--iodepth={self.iodepth}")
        if self.runtime > 0:
            argv.append(f"--runtime={self.runtime}s")
            argv.append("--time_based")
        argv.append(f"--rwmixread={self.rwmixread}")
        argv.append("--output-format=json")
        argv.append("--group_reporting")
        if self.direct:
            argv.append("--direct=1")
        argv.append(f"--readwrite={self.rwtype.value}")
        argv.append(f"--ioengine={self.ioengine.value}")
        argv.append(f"--numjobs={self.numjobs}")
        argv.append("--thread")
        # user_argument: space-split extra args appended verbatim
        for arg in self.extra_args:
            argv.extend(arg.split())
        size_bytes = _parse_size(self.size)
        if size_bytes is not None:
            argv.append(f"--size={size_bytes}")
        return argv


