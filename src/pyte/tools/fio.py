@dataclass(frozen=True)
class Percentiles:
    """clat percentile values (nanoseconds)."""
    p99_00: int
    p99_50: int
    p99_90: int
    p99_95: int


@dataclass(frozen=True)
class Lat:
    """lat_ns stats."""
    min_ns: int
    max_ns: int
    mean_ns: float
    stddev_ns: float


@dataclass(frozen=True)
class Clat:
    """clat_ns stats."""
    min_ns: int
    max_ns: int
    mean_ns: float
    stddev_ns: float
    percentiles: Percentiles


@dataclass(frozen=True)
class Bw:
    """Bandwidth stats (KiB/s)."""
    min: int
    max: int
    mean: float
    stddev: float


@dataclass(frozen=True)
class Iops:
    """IOPS stats."""
    min: int
    max: int
    mean: float
    stddev: float


@dataclass(frozen=True)
class IoStats:
    """Combined I/O stats for one direction (read or write)."""
    bandwidth: Bw
    iops: Iops
    latency: Lat
    clatency: Clat


@dataclass(frozen=True)
class Report:
    """Parsed fio JSON report: read and write stats from jobs[0]."""
    read: IoStats
    write: IoStats


# ---------------------------------------------------------------------------
# Parser
# ---------------------------------------------------------------------------

def _parse_bw(j: dict) -> Bw:
    return Bw(
        min=int(j["bw_min"]),
        max=int(j["bw_max"]),
        mean=float(j["bw_mean"]),
        stddev=float(j["bw_dev"]),
    )


def _parse_iops(j: dict) -> Iops:
    return Iops(
        min=int(j["iops_min"]),
        max=int(j["iops_max"]),
        mean=float(j["iops_mean"]),
        stddev=float(j["iops_stddev"]),
    )


def _parse_lat(j: dict) -> Lat:
    return Lat(
        min_ns=int(j["min"]),
        max_ns=int(j["max"]),
        mean_ns=float(j["mean"]),
        stddev_ns=float(j["stddev"]),
    )


def _parse_clat(j: dict) -> Clat:
    perc_obj = j.get("percentile")
    if perc_obj is not None:
        percentiles = Percentiles(
            p99_00=int(perc_obj["99.000000"]),
            p99_50=int(perc_obj["99.500000"]),
            p99_90=int(perc_obj["99.900000"]),
            p99_95=int(perc_obj["99.950000"]),
        )
    else:
        percentiles = Percentiles(p99_00=0, p99_50=0, p99_90=0, p99_95=0)
    return Clat(
        min_ns=int(j["min"]),
        max_ns=int(j["max"]),
        mean_ns=float(j["mean"]),
        stddev_ns=float(j["stddev"]),
        percentiles=percentiles,
    )


def _parse_io(j: dict) -> IoStats:
    return IoStats(
        bandwidth=_parse_bw(j),
        iops=_parse_iops(j),
        latency=_parse_lat(j["lat_ns"]),
        clatency=_parse_clat(j["clat_ns"]),
    )


def _parse_report(obj: dict) -> Report:
    """Parse a fio JSON output dict into a :class:`Report`.

    ``obj`` is the top-level dict (from ``json.loads()`` on fio's
    ``--output-format=json`` output).  Raises ``KeyError`` on missing
    fields or ``ValueError``/``TypeError`` on wrong value types.
    """
    first_job = obj["jobs"][0]
    return Report(
        read=_parse_io(first_job["read"]),
        write=_parse_io(first_job["write"]),
    )


# ---------------------------------------------------------------------------
# Fio: lifecycle class
# ---------------------------------------------------------------------------

class Fio:
    """Lifecycle manager for a running fio job.

    Normally created via :func:`run` which is a context manager.
    All I/O happens over ``pco.job("fio", argv)``; the JSON report
    arrives on stdout.  No shim imports: pure Python over pyte.job.
    """

    def __init__(self, job, stdout_filter):
        self._job = job
        self._stdout_filter = stdout_filter
        self._report: Report | None = None
        self._closed = False

    def wait(self, timeout: float = 120.0) -> Report:
        """Wait for fio to finish, parse JSON, return :class:`Report`.

        Caches the report; subsequent calls return the cached value.
        Raises :exc:`pyte.errors.FioError` on non-zero exit or JSON
        parse failure.
        """
        if self._report is not None:
            return self._report

        from pyte.errors import FioError
        from pyte.job import JobStatus

        status: JobStatus = self._job.wait(timeout=timeout)
        raw = self._stdout_filter.read_all(timeout=timeout)

        if not status.ok:
            raise FioError(
                f"fio exited with {status}; stdout={raw[:200]!r}")
        # fio may emit diagnostic lines (e.g. iodepth capped warnings)
        # to stdout before the JSON block.  Strip any prefix up to the
        # first '{' so json.loads sees only the JSON object.
        json_start = raw.find("{")
        if json_start > 0:
            raw = raw[json_start:]
        try:
            obj = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise FioError(
                f"cannot parse fio JSON output: {exc}; "
                f"stdout={raw[:200]!r}") from exc
        self._report = _parse_report(obj)
        return self._report

    def mi_report(self, tool: str = "fio") -> None:
        """Emit MI measurement artifacts mirroring tapi_fio_mi_report().

        KBYTE2MBIT(x) = x * 8 / 1000.0 (KiB/s → Mbit/s).

        Requires :meth:`wait` to have been called first.
        """
        if self._report is None:
            raise RuntimeError("call wait() before mi_report()")
        from pyte.mi import Aggr, Logger, Meas, Mult

        rep = self._report

        def kbyte2mbit(x: float) -> float:
            return x * 8 / 1000.0

        with Logger(tool) as logger:
            logger.add(Meas.THROUGHPUT, "Read throughput", Aggr.MEAN,
                       kbyte2mbit(rep.read.bandwidth.mean), Mult.MEBI)
            logger.add(Meas.IOPS, "Read iops", Aggr.MEAN,
                       rep.read.iops.mean, Mult.PLAIN)
            logger.add(Meas.LATENCY, "Read clat 99.00 percentile",
                       Aggr.PERCENTILE,
                       rep.read.clatency.percentiles.p99_00 / 1000.0,
                       Mult.MICRO)
            logger.add(Meas.THROUGHPUT, "Write throughput", Aggr.MEAN,
                       kbyte2mbit(rep.write.bandwidth.mean), Mult.MEBI)
            logger.add(Meas.IOPS, "Write iops", Aggr.MEAN,
                       rep.write.iops.mean, Mult.PLAIN)
            logger.add(Meas.LATENCY, "Write clat 99.00 percentile",
                       Aggr.PERCENTILE,
                       rep.write.clatency.percentiles.p99_00 / 1000.0,
                       Mult.MICRO)

    def close(self) -> None:
        """Stop fio (errors tolerated) and destroy the job (idempotent)."""
        if self._closed:
            return
        self._closed = True
        from pyte.errors import TeError
        try:
            self._job.stop()
        except TeError:
            pass
        self._job.destroy()


@contextmanager
def run(pco: "RpcServer", opts: Opts):
    """Context manager: create, start, and clean up a fio job.

    Yields a :class:`Fio` object; call :meth:`Fio.wait` inside the
    block to collect the report.  :meth:`Fio.close` is called on exit.

    Example::

        with fio.run(pco, opts) as f:
            rep = f.wait(timeout=60.0)
            print(rep.read.iops.mean)
    """
    job = pco.job("fio", opts.to_argv())
    try:
        # Attach a readable stdout filter for JSON collection.
        # fio writes the JSON report to stdout; stderr carries human-readable
        # progress and is forwarded to the TE log unread.  (C's fio_internal.c
        # reads stderr and logs stdout; pyte inverts this because the JSON
        # output arrives on stdout, not stderr.)
        stdout_filter = job.stdout.attach_filter(
            name="fio_stdout", readable=True)
        job.stderr.log(level="ERROR")
        job.start()
    except Exception:
        job.destroy()
        raise
    fio_obj = Fio(job, stdout_filter)
    try:
        yield fio_obj
    finally:
        fio_obj.close()
