"""pyte.tools.fio — run fio from Python tests via pyte.job.

Pure Python over pyte.job's public API; zero shim imports.
fio is resolved from the agent's PATH (the job program is ``"fio"``).
Gate fio tests with ``<req id="FIO"/>`` and the prologue probe.

Pinned mappings (derived from te/lib/tapi_fio/fio.c + fio_internal.c)
======================================================================

**argv mapping** (mirrors tapi_fio fio_binds order, relevant subset):

    --name=<name>
    --filename=<filename>
    --blocksize=<blocksize>
    --iodepth=<iodepth>
    --runtime=<N>s  --time_based     (only when runtime > 0; C emits --runtime=0s
                                     --time_based by default, pyte deliberately
                                     omits both when runtime <= 0)
    --rwmixread=<rwmixread>
    --output-format=json
    --group_reporting
    --direct=1                         (only when direct=True)
    --readwrite=<fio_rwtype>
        rwtype "rand"  → "randrw"
        rwtype "seq"   → "rw"
        rwtype "read"  → "read"
        rwtype "write" → "write"
        rwtype "trim"  → "trim"
        rwtype "randread"  → "randread"
        rwtype "randwrite" → "randwrite"
        rwtype "randtrim"  → "randtrim"
        rwtype "trimwrite" → "trimwrite"
    --ioengine=<ioengine>
        Accepted: sync, psync, vsync, pvsync, pvsync2, libaio, posixaio
    --numjobs=<numjobs>
    --thread
    <extra_args>  (raw, space-split, from user_argument() logic)
    --size=<size_bytes>

**JSON report paths** (from get_report/get_report_io in fio.c):

    jobs[0].read.bw_max           → read.bandwidth.max   (int, KiB/s)
    jobs[0].read.bw_min           → read.bandwidth.min   (int, KiB/s)
    jobs[0].read.bw_mean          → read.bandwidth.mean  (float, KiB/s)
    jobs[0].read.bw_dev           → read.bandwidth.stddev (float, KiB/s)
    jobs[0].read.iops_min         → read.iops.min        (int)
    jobs[0].read.iops_max         → read.iops.max        (int)
    jobs[0].read.iops_mean        → read.iops.mean       (float)
    jobs[0].read.iops_stddev      → read.iops.stddev     (float)
    jobs[0].read.lat_ns.min       → read.latency.min_ns  (int)
    jobs[0].read.lat_ns.max       → read.latency.max_ns  (int)
    jobs[0].read.lat_ns.mean      → read.latency.mean_ns (float)
    jobs[0].read.lat_ns.stddev    → read.latency.stddev_ns (float)
    jobs[0].read.clat_ns.min      → read.clatency.min_ns
    jobs[0].read.clat_ns.max      → read.clatency.max_ns
    jobs[0].read.clat_ns.mean     → read.clatency.mean_ns
    jobs[0].read.clat_ns.stddev   → read.clatency.stddev_ns
    jobs[0].read.clat_ns.percentile."99.000000"  → read.clatency.percentiles.p99_00
    jobs[0].read.clat_ns.percentile."99.500000"  → read.clatency.percentiles.p99_50
    jobs[0].read.clat_ns.percentile."99.900000"  → read.clatency.percentiles.p99_90
    jobs[0].read.clat_ns.percentile."99.950000"  → read.clatency.percentiles.p99_95
    (same for write.*)
    Note: TE's C code truncates the percentile key lookup via ``int / 1000``
    whereas pyte keeps the fraction (deliberate improvement); values may
    differ from C runs when fio's JSON key layout does not align with an
    exact integer boundary.

**MI mapping** (from tapi_fio_mi_report, tapi_fio.c:266-283):

    KBYTE2MBIT(x) = x * 8 / 1000.0   (KiB/s → Mbit/s)

    THROUGHPUT "Read throughput"          MEAN  KBYTE2MBIT(read.bandwidth.mean)   MEBI
    IOPS       "Read iops"                MEAN  read.iops.mean                    PLAIN
    LATENCY    "Read clat 99.00 percentile" PERCENTILE
               read.clatency.percentiles.p99_00 / 1000  MICRO
    THROUGHPUT "Write throughput"         MEAN  KBYTE2MBIT(write.bandwidth.mean)  MEBI
    IOPS       "Write iops"               MEAN  write.iops.mean                   PLAIN
    LATENCY    "Write clat 99.00 percentile" PERCENTILE
               write.clatency.percentiles.p99_00 / 1000 MICRO

**Fixture provenance:**
    lib/pyte/tests/data/fio_sample.json was generated by running fio directly
    on host ``test`` (passwordless SSH):
        fio --name=pyte_sample --filename=/tmp/pyte_fio_sample.dat
            --size=4m --bs=4096 --rw=randrw --rwmixread=50
            --iodepth=4 --runtime=2 --time_based --ioengine=psync
            --output-format=json
    fio version: fio-3.39.  The JSON paths and value types are pinned from
    this real output, not from hand-rolled samples.
"""
